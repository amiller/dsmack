def materialize(config,packet,key_id,parent,fetch):
    """Server prepares signed per-attempt inputs; only local paths are generated here."""
    parent=protected(parent,True);need(re.fullmatch('[a-f0-9]{32}',packet['attempt_id']) and packet['key_id']==key_id,'attempt/key binding')
    need(packet['profile_id']==config['profile_id'],'unexpected checker profile')
    need(packet['release_inventory_sha256']==pin(config['inventory'])['sha256'],'unexpected release')
    rows=packet['artifacts'];names={'closure-context.json','checker-context.json','workload-admission.json','workload.sig','workload.img'}
    need(type(rows)is list and len(rows)==len(names) and {d['name'] for d in rows}==names,'closed portable artifact membership')
    dest=parent/packet['attempt_id'];dest.mkdir(mode=0o700);pins={}
    for d in rows:
        need(set(d)=={'name','bytes','sha256','url'} and type(d['bytes'])is int and 0<d['bytes']<=(4<<30) and re.fullmatch('[a-f0-9]{64}',d['sha256']),'artifact descriptor')
        path=dest/d['name'];fetch(d,path);pins[d['name']]=pin(path,4<<30);need(all(pins[d['name']][k]==d[k] for k in ('bytes','sha256')),'download changed')
    closure=document(read(dest/'closure-context.json',65536));checker=document(read(dest/'checker-context.json',65536))
    need(closure['attempt_id']==packet['native_execution_id'] and checker['expected']['closure_context']==closure and checker['expected']['key_id_b64']==key_id and checker['expected']['manifest_sha256']==packet['manifest_sha256'],'task context mismatch')
    challenge=base64.b64decode(packet['challenge_b64'],validate=True);need(len(challenge)==32 and checker['expected']['challenge']==challenge.hex(),'task challenge mismatch')
    task={'schema':'dsmack-alpha-local-task/2','profile_id':config['profile_id'],'closure_context':pins['closure-context.json'],'checker_context':pins['checker-context.json'],'challenge':exclusive(dest/'challenge.bin',challenge),'key_id':exclusive(dest/'keyId.txt',key_id.encode()),'workload_disk':pins['workload.img'],'workload_admission':pins['workload-admission.json'],'workload_signature':pins['workload.sig']}
    exclusive(dest/'task.json',canonical(task));exclusive(dest/'execution-packet.json',canonical(packet))
    # Full original signature/disk/closure validation, not HTTPS alone, authorizes preparation.
    alpha,auth,checked=release(config);c,_,_=alpha['selected_modules'](config['install_root'],checked);alpha['validate_workload'](auth,config['install_root'],checked,task,c)
    return dest/'task.json'

def coordinator(config,command,task_path,run_parent,attempt_id):
    need(command in ('prepare','check','run','resume')and re.fullmatch('[a-f0-9]{32}',attempt_id),'unsupported command/native identity');release(config)
    plan=Path(run_parent)/('attempt-'+attempt_id+'.control')/'plan.json'
    auth={k:pin(config[k]) for k in ('bootstrap','inventory','signature')}
    if command!='prepare':
        expected={'schema':'dsmack-alpha-launch-plan/1','admission':auth,'root':config['install_root'],'profile_id':config['profile_id'],'task':pin(task_path),'out_parent':str(run_parent),'inventory_sha256':auth['inventory']['sha256'],'attempt_id':attempt_id}
        need(document(read(plan,65536))==expected,'saved plan differs from admitted task')
    args=[sys.executable,'-I','-B',str(Path(config['install_root'])/'alpha_coordinator.py')]
    if command=='prepare':args+=['--prepare',*sum((["--"+k,config[k]] for k in ('bootstrap','inventory','signature')),[]),'--root',config['install_root'],'--profile',config['profile_id'],'--task',str(task_path),'--out-parent',str(run_parent)]
    else:args+=[{'check':'--check-only','run':'--execute','resume':'--resume'}[command],'--plan',str(plan)]
    return subprocess.run(args,env={'HOME':str(Path.home()),'PATH':'/usr/bin:/bin'},timeout=1320).returncode

