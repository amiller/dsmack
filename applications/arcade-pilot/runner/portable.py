def need(ok, message):
    if not ok: raise ValueError(message)

def canonical(v): return json.dumps(v,sort_keys=True,separators=(',',':'),ensure_ascii=False,allow_nan=False).encode()

def document(raw):
    def pairs(rows):
        d={}
        for k,v in rows:
            need(k not in d,'duplicate JSON key');d[k]=v
        return d
    return json.loads(raw,object_pairs_hook=pairs)

def protected(path, directory=False):
    p=Path(path);need(p.is_absolute() and '..' not in p.parts,'absolute protected local path required')
    for q in (p,*p.parents):
        s=q.lstat();need(not stat.S_ISLNK(s.st_mode) and s.st_uid in (0,os.getuid()) and not s.st_mode&0o022,'unprotected local path')
    s=p.lstat();need(stat.S_ISDIR(s.st_mode) if directory else stat.S_ISREG(s.st_mode) and s.st_nlink==1,'wrong local file type')
    return p

def read(path,cap=1<<20):
    p=protected(path);fd=os.open(p,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    with os.fdopen(fd,'rb') as f:
        s=os.fstat(f.fileno());need(stat.S_ISREG(s.st_mode) and s.st_nlink==1 and s.st_size<=cap,'bounded regular file required');b=f.read(cap+1)
        need(len(b)==s.st_size,'file changed');return b

def exclusive(path,raw):
    p=Path(path);protected(p.parent,True);fd=os.open(p,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
    with os.fdopen(fd,'wb') as f:f.write(raw);f.flush();os.fsync(f.fileno())
    return pin(p)

def pin(path,cap=1<<30):
    p=protected(path);h=hashlib.sha256();n=0
    with p.open('rb') as f:
        before=os.fstat(f.fileno())
        for b in iter(lambda:f.read(4<<20),b''):n+=len(b);need(n<=cap,'file cap');h.update(b)
        after=os.fstat(f.fileno())
    need((before.st_ino,before.st_size,before.st_mtime_ns,before.st_ctime_ns)==(after.st_ino,after.st_size,after.st_mtime_ns,after.st_ctime_ns) and n==before.st_size,'file changed')
    return {'path':str(p),'bytes':n,'sha256':h.hexdigest()}

def selected(path,digest):
    b=read(path,262144);need(hashlib.sha256(b).hexdigest()==digest,'selected source changed');ns={'__name__':'arcade_selected','__file__':str(path)};exec(compile(b,str(path),'exec'),ns);return ns

