/// Errors associated with the VMM internal logic. These errors cannot be generated by direct user
/// input, but can result from bad configuration of the host (for example if Firecracker doesn't
/// have permissions to open the KVM fd).
#[derive(Debug)]
#[allow(unused)]
pub enum Error {
    /// This error is thrown by the minimal boot loader implementation.
    ConfigureSystem(arch::Error),
    /// Legacy devices work with Event file descriptors and the creation can fail because
    /// of resource exhaustion.
    #[cfg(target_arch = "x86_64")]
    CreateLegacyDevice(device_manager::legacy::Error),
    /// Cannot read from an Event file descriptor.
    EventFd(io::Error),
    /// Cannot open /dev/kvm. Either the host does not have KVM or Firecracker does not have
    /// permission to open the file descriptor.
    KvmContext(vstate::Error),
    #[cfg(target_arch = "x86_64")]
    /// Cannot add devices to the Legacy I/O Bus.
    LegacyIOBus(device_manager::legacy::Error),
    /// Cannot add a device to the MMIO Bus.
    RegisterMMIODevice(device_manager::mmio::Error),
    #[cfg(any(target_arch = "aarch64", target_arch = "riscv64"))]
    /// Cannot generate or write FDT
    SetupFDT(devices::fdt::Error),
    /// Vcpu error.
    Vcpu(vstate::Error),
    /// Cannot send event to vCPU.
    VcpuEvent(vstate::Error),
    /// Cannot create a vCPU handle.
    VcpuHandle(vstate::Error),
    /// vCPU resume failed.
    VcpuResume,
    /// Vm error.
    Vm(vstate::Error),
}

impl Display for Error {
    fn fmt(&self, f: &mut Formatter) -> std::fmt::Result {
        use self::Error::*;

        match self {
            ConfigureSystem(e) => write!(f, "System configuration error: {e:?}"),
            #[cfg(target_arch = "x86_64")]
            CreateLegacyDevice(e) => write!(f, "Error creating legacy device: {e:?}"),
            EventFd(e) => write!(f, "Event fd error: {e}"),
            KvmContext(e) => write!(f, "Failed to validate KVM support: {e:?}"),
            #[cfg(target_arch = "x86_64")]
            LegacyIOBus(e) => write!(f, "Cannot add devices to the legacy I/O Bus. {e}"),
            RegisterMMIODevice(e) => write!(f, "Cannot add a device to the MMIO Bus. {e}"),
            #[cfg(any(target_arch = "aarch64", target_arch = "riscv64"))]
            SetupFDT(e) => write!(f, "Error generating or writing FDT: {e:?}"),
            Vcpu(e) => write!(f, "Vcpu error: {e}"),
            VcpuEvent(e) => write!(f, "Cannot send event to vCPU. {e:?}"),
            VcpuHandle(e) => write!(f, "Cannot create a vCPU handle. {e}"),
            VcpuResume => write!(f, "vCPUs resume failed."),
            Vm(e) => write!(f, "Vm error: {e}"),
        }
    }
}

/// Shorthand result type for internal VMM commands.
pub type Result<T> = std::result::Result<T, Error>;

/// Contains the state and associated methods required for the Firecracker VMM.
pub struct Vmm {
    // Guest VM core resources.
    pub(crate) guest_memory: GuestMemoryMmap,
    pub(crate) arch_memory_info: ArchMemoryInfo,

    pub(crate) kernel_cmdline: KernelCmdline,

    pub(crate) vcpus_handles: Vec<VcpuHandle>,
    pub(crate) exit_evt: EventFd,
    #[cfg(not(target_os = "windows"))]
    pub(crate) vm: Vm,
    pub(crate) exit_observers: Vec<Arc<Mutex<dyn VmmExitObserver>>>,
    pub(crate) exit_code: Arc<AtomicI32>,

    // Guest VM devices.
    pub(crate) mmio_device_manager: MMIODeviceManager,

    // Out-of-band live pause/resume requests: the C API sends `VmCtl` from
    // another thread; the event loop freezes or wakes the vCPUs. A single
    // channel rather than one eventfd per operation, so the event loop observes
    // the requests in the order they were made. Device worker threads are
    // notify-driven, so a frozen guest leaves them idle without explicit
    // handling.
    #[cfg(target_os = "macos")]
    pub(crate) vm_ctl_tx: PollableChannelSender<VmCtl>,
    #[cfg(target_os = "macos")]
    pub(crate) vm_ctl_rx: PollableChannelReciever<VmCtl>,
    #[cfg(target_os = "macos")]
    pub(crate) paused: bool,
    #[cfg(target_os = "macos")]
    pub(crate) paused_at: u64,
    // Returning lifecycle. `halted` is set once by the exit event: `Some(None)` means no vCPU
    // reported `Exited`, which is never treated as success.
    #[cfg(target_os = "macos")]
    pub(crate) returning: bool,
    #[cfg(target_os = "macos")]
    pub(crate) halted: Option<Option<u8>>,
    /// dsmack v3 F09 — the execution deadline, armed at vCPU start. `None` means
    /// no budget was requested. The returning run loop fails closed once this
    /// elapses, so a guest that never halts cannot execute indefinitely.
    #[cfg(target_os = "macos")]
    pub(crate) exec_deadline: Option<std::time::Instant>,
    /// dsmack v3 F09 — the INDEPENDENT execution-budget watchdog's completion
    /// latch. `Some(false)` while the guest is within budget; set to `true` only
    /// once the returning run observed a halt WITHIN the deadline (so teardown is
    /// not aborted). The watchdog thread (armed at vCPU start, see
    /// [`Vmm::arm_exec_watchdog`]) fails the process CLOSED if the deadline
    /// elapses before this latch is set — enforcing the budget even if `run` is
    /// never called.
    #[cfg(target_os = "macos")]
    pub(crate) exec_watchdog_done: Option<std::sync::Arc<std::sync::atomic::AtomicBool>>,
}

/// dsmack v3 F09 — the exit code reported when the returning execution budget is
/// exhausted before the guest halts. Distinct from a guest PSCI halt (0) and
/// from any ordinary vCPU exit, so the backend can refuse to claim success.
#[cfg(target_os = "macos")]
pub(crate) const EXEC_BUDGET_EXCEEDED_CODE: u8 = 124;

/// Out-of-band request to the running VM's event loop.
#[cfg(target_os = "macos")]
#[derive(Debug, Clone)]
pub enum VmCtl {
    Pause,
    Resume,
}

/// Fails closed on a returning-lifecycle fault that cannot be reported as a
/// normal error (abnormal vCPU termination, a built VM dropped before its
/// returning run, teardown that cannot complete). Aborting guarantees the
/// fault suppresses a successful return: no exit code, no receipt.
pub(crate) fn returning_unrecoverable(msg: &str) -> ! {
    // Fatal enforcement must not wait for a logger or a full diagnostic pipe.
    unsafe {
        let flags = libc::fcntl(libc::STDERR_FILENO, libc::F_GETFL);
        if flags >= 0 && libc::fcntl(libc::STDERR_FILENO, libc::F_SETFL, flags | libc::O_NONBLOCK) == 0 {
            for bytes in [b"DSMACK_RETURNING_UNRECOVERABLE ".as_slice(), msg.as_bytes(), b"\n".as_slice()] {
                let _ = libc::write(libc::STDERR_FILENO, bytes.as_ptr().cast(), bytes.len());
            }
        }
    }
    std::process::abort()
}

impl Vmm {
    /// dsmack v3 F09 — arm the INDEPENDENT execution-budget watchdog. Spawns a
    /// detached supervisor thread that is NOT coupled to any later `run` call:
    /// it sleeps in short slices until `exec_deadline` and, if the deadline
    /// elapses before [`cancel_exec_watchdog`] marks an in-budget halt, it fails
    /// the process CLOSED (`returning_unrecoverable`). This closes the F09
    /// defect where a caller could retain a built VM without calling `run` and
    /// leave the guest executing indefinitely: the budget starts at vCPU start
    /// and is enforced regardless of whether `run` is ever invoked. No-op when
    /// no budget was requested (non-returning profiles).
    #[cfg(target_os = "macos")]
    pub fn arm_exec_watchdog(&mut self) {
        use std::sync::atomic::Ordering;
        let Some(deadline) = self.exec_deadline else {
            return;
        };
        if self.exec_watchdog_done.is_some() {
            return; // already armed
        }
        let done = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
        self.exec_watchdog_done = Some(done.clone());
        std::thread::Builder::new()
            .name("dsmack-exec-watchdog".into())
            .spawn(move || {
                let slice = std::time::Duration::from_millis(50);
                loop {
                    if done.load(Ordering::SeqCst) {
                        return; // in-budget halt observed; teardown proceeds
                    }
                    if std::time::Instant::now() >= deadline {
                        // Deadline reached before an in-budget halt: permanently
                        // fail closed. Re-check `done` once more to avoid racing a
                        // halt that set it in the same instant.
                        if done.load(Ordering::SeqCst) {
                            return;
                        }
                        returning_unrecoverable(
                            "execution budget exceeded (independent watchdog): the admitted \
                             execution budget elapsed before the guest halted; failing closed \
                             (no result is produced), enforced regardless of any run() call",
                        );
                    }
                    std::thread::sleep(slice);
                }
            })
            .expect("spawn dsmack-exec-watchdog");
    }

    /// dsmack v3 F09 — mark the execution budget as satisfied by an IN-BUDGET
    /// halt, so the independent watchdog exits without aborting and the
    /// subsequent (separately-bounded) teardown is not killed. MUST be called
    /// only after confirming the deadline had not already elapsed.
    #[cfg(target_os = "macos")]
    pub fn cancel_exec_watchdog(&self) {
        if let Some(done) = &self.exec_watchdog_done {
            done.store(true, std::sync::atomic::Ordering::SeqCst);
        }
    }

    /// Starts the microVM vcpus.
    pub fn start_vcpus(&mut self, mut vcpus: Vec<Vcpu>) -> Result<()> {
        let vcpu_count = vcpus.len();

        Vcpu::register_kick_signal_handler();

        self.vcpus_handles.reserve(vcpu_count);

        for mut vcpu in vcpus.drain(..) {
            vcpu.set_mmio_bus(self.mmio_device_manager.bus.clone());

            self.vcpus_handles
                .push(vcpu.start_threaded().map_err(Error::VcpuHandle)?);
        }

        // The vcpus start off in the `Paused` state, let them run.
        self.resume_vcpus()?;

        Ok(())
    }

    /// Sends a resume command to the vcpus.
    #[cfg(target_os = "linux")]
    pub fn resume_vcpus(&mut self) -> Result<()> {
        for handle in self.vcpus_handles.iter() {
            handle
                .send_event(VcpuEvent::Resume)
                .map_err(Error::VcpuEvent)?;
        }
        for handle in self.vcpus_handles.iter() {
            match handle
                .response_receiver()
                .recv_timeout(Duration::from_millis(1000))
            {
                Ok(VcpuResponse::Resumed) => (),
                _ => return Err(Error::VcpuResume),
            }
        }
        Ok(())
    }

    #[cfg(target_os = "macos")]
    pub fn resume_vcpus(&mut self) -> Result<()> {
        Ok(())
    }

    #[cfg(target_os = "windows")]
    pub fn resume_vcpus(&mut self) -> Result<()> {
        for handle in self.vcpus_handles.iter() {
            handle
                .send_event(VcpuEvent::Resume)
                .map_err(Error::VcpuEvent)?;
        }
        for handle in self.vcpus_handles.iter() {
            match handle
                .response_receiver()
                .recv_timeout(Duration::from_millis(1000))
            {
                Ok(VcpuResponse::Resumed) => (),
                _ => return Err(Error::VcpuResume),
            }
        }
        Ok(())
    }

    /// Sender for live [`VmCtl`] requests. The event loop runs [`Vmm::pause`] /
    /// [`Vmm::resume`] in response.
    #[cfg(target_os = "macos")]
    pub fn vm_ctl_sender(&self) -> PollableChannelSender<VmCtl> {
        self.vm_ctl_tx.clone()
    }

    /// Freeze every vCPU at an instruction boundary. Reversible via [`Vmm::resume`];
    /// the guest's virtual counter is held so timers don't fire en masse on wake.
    /// Idempotent: pausing an already-paused VM is a no-op.
    #[cfg(target_os = "macos")]
    pub fn pause(&mut self) -> std::result::Result<(), String> {
        use crate::vmm::vstate::{VcpuEvent, VcpuResponse};
        if self.paused {
            return Ok(());
        }
        for h in &self.vcpus_handles {
            h.send_event(VcpuEvent::Pause)
                .map_err(|e| format!("vcpu pause event: {e:?}"))?;
            hvf::vcpu_request_exit(h.hvf_id()).map_err(|e| format!("vcpu_request_exit: {e:?}"))?;
        }
        for h in &self.vcpus_handles {
            match h.response_receiver().recv() {
                Ok(VcpuResponse::Paused) => {}
                Ok(other) => return Err(format!("unexpected vcpu response: {other:?}")),
                Err(e) => return Err(format!("vcpu response: {e:?}")),
            }
        }
        self.paused_at = unsafe { hvf::mach_absolute_time() };
        self.paused = true;
        Ok(())
    }

    /// Wake every vCPU previously frozen by [`Vmm::pause`], advancing the vtimer
    /// offset by the time spent paused. Idempotent: resuming a running VM is a
    /// no-op.
    #[cfg(target_os = "macos")]
    pub fn resume(&mut self) -> std::result::Result<(), String> {
        use crate::vmm::vstate::{VcpuEvent, VcpuResponse};
        if !self.paused {
            return Ok(());
        }
        let paused_ticks = unsafe { hvf::mach_absolute_time() }.saturating_sub(self.paused_at);
        for h in &self.vcpus_handles {
            h.send_event(VcpuEvent::Resume(paused_ticks))
                .map_err(|e| format!("vcpu resume event: {e:?}"))?;
        }
        for h in &self.vcpus_handles {
            match h.response_receiver().recv() {
                Ok(VcpuResponse::Resumed) => {}
                Ok(other) => return Err(format!("unexpected vcpu response: {other:?}")),
                Err(e) => return Err(format!("vcpu response: {e:?}")),
            }
        }
        self.paused = false;
        Ok(())
    }

    /// Configures the system for boot.
    #[allow(clippy::too_many_arguments)]
    pub fn configure_system(
        &self,
        vcpus: &[Vcpu],
        _intc: &IrqChip,
        initrd: &Option<InitrdConfig>,
        _smbios_oem_strings: &Option<Vec<String>>,
        _acpi_enabled: bool,
        _virtio_mmio_devices: &[(u64, u32)],
        _pvh: bool,
    ) -> Result<()> {
        #[cfg(target_arch = "x86_64")]
        {
            let cmdline_len = if cfg!(feature = "tee") {
                arch::x86_64::layout::CMDLINE_SEV_SIZE
            } else {
                self.kernel_cmdline.len() + 1
            };

            arch::x86_64::configure_system(
                &self.guest_memory,
                &self.arch_memory_info,
                vm_memory::GuestAddress(arch::x86_64::layout::CMDLINE_START),
                cmdline_len,
                initrd,
                vcpus.len() as u8,
                _pvh,
                _acpi_enabled,
                _virtio_mmio_devices,
            )
            .map_err(Error::ConfigureSystem)?;
        }

        #[cfg(target_arch = "aarch64")]
        {
            let vcpu_mpidr = vcpus.iter().map(|cpu| cpu.get_mpidr()).collect();
            fdt::create_fdt(
                &self.guest_memory,
                &self.arch_memory_info,
                vcpu_mpidr,
                self.kernel_cmdline.as_str(),
                self.mmio_device_manager.get_device_info(),
                _intc,
                initrd,
            )
            .map_err(Error::SetupFDT)?;
        }

        #[cfg(target_arch = "aarch64")]
        {
            arch::aarch64::configure_system(
                &self.guest_memory,
                &self.arch_memory_info,
                _smbios_oem_strings,
            )
            .map_err(Error::ConfigureSystem)?;
        }

        #[cfg(target_arch = "riscv64")]
        {
            fdt::create_fdt(
                &self.guest_memory,
                &self.arch_memory_info,
                vcpus.len() as u32,
                self.kernel_cmdline.as_str(),
                self.mmio_device_manager.get_device_info(),
                _intc,
                initrd,
            )
            .map_err(Error::SetupFDT)?;

            arch::riscv64::configure_system(&self.guest_memory, _smbios_oem_strings)
                .map_err(Error::ConfigureSystem)?;
        }

        Ok(())
    }

    /// Returns a reference to the inner `GuestMemoryMmap` object if present, or `None` otherwise.
    pub fn guest_memory(&self) -> &GuestMemoryMmap {
        &self.guest_memory
    }

    /// Waits for all vCPUs to exit and terminates the Firecracker process.
    pub fn stop(&mut self, exit_code: i32) {
        info!("Vmm is stopping.");

        for observer in &self.exit_observers {
            observer
                .lock()
                .expect("Poisoned mutex for exit observer")
                .on_vmm_exit();
        }

        // Exit from Firecracker using the provided exit code. Safe because we're terminating
        // the process anyway.
        unsafe {
            libc::_exit(exit_code);
        }
    }

    /// Returning lifecycle, phase 1, called with the event loop stopped after `halted` is set.
    /// The sole vCPU has reported `Exited` and is parked outside `hv_vcpu_run`, still a valid
    /// interrupt target. Exit observers stop the console port workers (joining them, which may
    /// inject guest interrupts); a worker panic, writer error or teardown timeout fails the
    /// teardown so no exit code can be reported. Then each vCPU is destroyed on its own thread
    /// and joined.
    #[cfg(target_os = "macos")]
    pub(crate) fn stop_returning(&mut self) -> std::result::Result<u8, String> {
        let code = match self.halted {
            Some(Some(code)) => code,
            Some(None) => return Err("exit event without vCPU Exited response".into()),
            None => return Err("VMM has not halted".into()),
        };
        for observer in self.exit_observers.drain(..) {
            observer
                .lock()
                .map_err(|_| "poisoned exit observer")?
                .on_vmm_exit_checked()
                .map_err(|e| format!("exit observer: {e}"))?;
        }
        for handle in &mut self.vcpus_handles {
            handle.destroy_and_join(std::time::Duration::from_secs(5))?;
        }
        Ok(code)
    }

    /// Returning lifecycle, phase 2, on the sole remaining owner after the event manager and
    /// every other device owner are gone: drop device owners, destroy the HVF VM while guest
    /// memory is still mapped, then drop guest memory. The guest mapping is released only
    /// after destruction succeeded; on failure (and on unwind) ownership is retained.
    #[cfg(target_os = "macos")]
    pub(crate) fn finish_returning(self) -> Result<()> {
        let Vmm {
            guest_memory,
            vm,
            mmio_device_manager,
            vcpus_handles,
            exit_observers,
            ..
        } = self;
        drop((mmio_device_manager, vcpus_handles, exit_observers));
        destroy_then_release_guest_memory(
            || vm.destroy().map_err(Error::Vm),
            std::mem::ManuallyDrop::new(guest_memory),
        )
    }

    /// Returns a reference to the inner KVM Vm object.
    #[cfg(feature = "tee")]
    pub fn kvm_vm(&self) -> &Vm {
        &self.vm
    }

    #[cfg(target_os = "macos")]
    pub fn add_mapping(
        &self,
        reply_sender: Sender<bool>,
        host_addr: u64,
        guest_addr: u64,
        len: u64,
    ) {
        self.vm
            .add_mapping(reply_sender, host_addr, guest_addr, len);
    }

    #[cfg(target_os = "macos")]
    pub fn remove_mapping(&self, reply_sender: Sender<bool>, guest_addr: u64, len: u64) {
        self.vm.remove_mapping(reply_sender, guest_addr, len);
    }
}

/// Release ordering for the returning lifecycle (R2-A7-MEMORY-LIFETIME): the
/// guest mapping must be released strictly after hypervisor destruction
/// succeeded — never before, on any path. On macOS the hypervisor holds
/// references to the mapped pages until `hv_vm_destroy` succeeds; the previous
/// `?`-then-drop ordering released them before the failure could reach the
/// fail-closed caller, leaving a dangling mapping behind a still-running
/// process.
///
/// Wrapping the memory in `ManuallyDrop` at the call site keeps ownership in
/// the caller's frame across error returns AND unwinds (a panic inside
/// `destroy` unwinds into `run_returning`'s `catch_unwind`, whose guard aborts
/// — even that unwind must not unmap the pages). On success this is the
/// single, final release. On destruction failure the wrapper drops without
/// taking, which retains the mapping for the process lifetime: the
/// returning-profile caller aborts via `unrecoverable` immediately after
/// receiving this error, and until then no path can release the mapping.
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
pub(crate) fn destroy_then_release_guest_memory<E>(
    destroy: impl FnOnce() -> std::result::Result<(), E>,
    mut guest_memory: std::mem::ManuallyDrop<GuestMemoryMmap>,
) -> std::result::Result<(), E> {
    match destroy() {
        Ok(()) => {
            // Destruction succeeded; take and release exactly once.
            drop(unsafe { std::mem::ManuallyDrop::take(&mut guest_memory) });
            Ok(())
        }
        Err(e) => {
            // Destruction failed: the wrapper drops here WITHOUT releasing the
            // mapping. Retained deliberately; this path never releases.
            Err(e)
        }
    }
}

impl Subscriber for Vmm {
    /// Handle a read event (EPOLLIN).
    fn process(&mut self, event: &EpollEvent, _: &mut EventManager) {
        let source = event.fd();
        let event_set = event.event_set();

        #[cfg(target_os = "macos")]
        if source == self.vm_ctl_rx.as_raw_fd() && event_set == EventSet::IN {
            while let Ok(Some(req)) = self.vm_ctl_rx.try_recv() {
                let res = match req {
                    VmCtl::Pause => self.pause(),
                    VmCtl::Resume => self.resume(),
                };
                if let Err(e) = res {
                    error!("vm {req:?} failed: {e}");
                }
            }
            return;
        }

        if source == self.exit_evt.as_raw_fd() && event_set == EventSet::IN {
            let _ = self.exit_evt.read();
            #[cfg(target_os = "macos")]
            if self.returning {
                if self.halted.is_none() {
                    self.halted = Some(self.vcpus_handles.iter().find_map(|handle| {
                        match handle.response_receiver().try_recv() {
                            Ok(VcpuResponse::Exited(exit_code)) => Some(exit_code),
                            _ => None,
                        }
                    }));
                }
                return;
            }
            // Query each vcpu for the exit_code.
            // If the exit_code can't be found on any vcpu, it means that the exit signal
            // has been issued by the i8042 controller in which case we exit with
            // FC_EXIT_CODE_OK.
            //
            // The exit code set up by the guest takes preference over the one reported
            // by either a vcpu or the i8042 controller.
            let vcpu_exit_code = self
                .vcpus_handles
                .iter()
                .find_map(|handle| match handle.response_receiver().try_recv() {
                    Ok(VcpuResponse::Exited(exit_code)) => Some(exit_code),
                    _ => None,
                })
                .unwrap_or(FC_EXIT_CODE_OK);
            let vmm_exit_code = self.exit_code.load(Ordering::SeqCst);
            let exit_code = if vmm_exit_code != i32::MAX {
                debug!("using vmm exit code: {vmm_exit_code}");
                vmm_exit_code
            } else {
                debug!("using vcpu exit code: {vcpu_exit_code}");
                vcpu_exit_code as i32
            };
            self.stop(exit_code);
        } else {
            error!("Spurious EventManager event for handler: Vmm");
        }
    }

    fn interest_list(&self) -> Vec<EpollEvent> {
        // `vm_ctl_rx` is pushed only on macOS, so `mut` is unused elsewhere.
        #[allow(unused_mut)]
        let mut list = vec![EpollEvent::new(
            EventSet::IN,
            self.exit_evt.as_raw_fd() as u64,
        )];
        #[cfg(target_os = "macos")]
        list.push(EpollEvent::new(
            EventSet::IN,
            self.vm_ctl_rx.as_raw_fd() as u64,
        ));
        list
    }
}

#[cfg(test)]
mod memory_lifetime_tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering as AtomicOrdering};
    use std::sync::Arc;
    use vm_memory::{GuestAddress, GuestMemoryBackend};

    fn one_page_memory() -> GuestMemoryMmap {
        GuestMemoryMmap::from_ranges(&[(GuestAddress(0), 4096)]).expect("one-page guest mapping")
    }

    /// True when some mapping in /proc/self/maps covers `host_addr` (Linux
    /// test host): the direct observation of whether the guest mapping was
    /// released.
    fn addr_is_mapped(host_addr: usize) -> bool {
        let maps = std::fs::read_to_string("/proc/self/maps").expect("own /proc/self/maps");
        maps.lines().any(|line| {
            let mut bounds = line.split_whitespace().next().unwrap_or("").splitn(2, '-');
            let start = usize::from_str_radix(bounds.next().unwrap_or(""), 16).unwrap_or(0);
            let end = usize::from_str_radix(bounds.next().unwrap_or(""), 16).unwrap_or(0);
            host_addr >= start && host_addr < end
        })
    }

    /// R2-A7 failure injection: when destruction fails, the error propagates
    /// unchanged, destruction is attempted exactly once, and the guest mapping
    /// is still present and usable afterwards. On the previously-defective
    /// ordering the mapping was dropped before the error returned, so both the
    /// maps check and the volatile write/read through the pre-taken host
    /// pointer would fail on an unmapped page.
    #[test]
    fn failed_destroy_retains_guest_memory() {
        let destroy_calls = Arc::new(AtomicUsize::new(0));
        let calls = Arc::clone(&destroy_calls);
        let memory = one_page_memory();
        let host_ptr =
            memory.get_host_address(GuestAddress(0)).expect("host address") as *mut u64;
        assert!(addr_is_mapped(host_ptr as usize));
        let memory = std::mem::ManuallyDrop::new(memory);
        let result = destroy_then_release_guest_memory(
            move || {
                calls.fetch_add(1, AtomicOrdering::SeqCst);
                Err("injected hv_vm_destroy failure")
            },
            memory,
        );
        assert_eq!(result, Err("injected hv_vm_destroy failure"));
        assert_eq!(destroy_calls.load(AtomicOrdering::SeqCst), 1);
        // The mapping must still be live after the failed destruction.
        assert!(addr_is_mapped(host_ptr as usize));
        unsafe {
            host_ptr.write_volatile(0x444D_5341_434B_2131);
            assert_eq!(host_ptr.read_volatile(), 0x444D_5341_434B_2131);
        }
    }

    /// Success path: destruction happens first (the only event) and only then
    /// is the mapping released — observed as the /proc/self/maps range for the
    /// pre-taken host address disappearing after the Ok return. The mapping is
    /// never touched after release (release is terminal).
    #[test]
    fn successful_destroy_releases_after_destruction() {
        let memory = one_page_memory();
        let host_addr = memory.get_host_address(GuestAddress(0)).expect("host address") as usize;
        assert!(addr_is_mapped(host_addr));
        let memory = std::mem::ManuallyDrop::new(memory);
        let result = destroy_then_release_guest_memory::<()>(|| Ok(()), memory);
        assert_eq!(result, Ok(()));
        assert!(!addr_is_mapped(host_addr));
    }
}
